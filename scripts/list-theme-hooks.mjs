// Regenerates docs/theme-hooks.md: every CSS class the launcher renders (the surface a theme can style),
// and every design token with its default. Run: node scripts/list-theme-hooks.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const walk = (dir) => readdirSync(dir).flatMap((name) => {
  const path = join(dir, name);
  return statSync(path).isDirectory() ? walk(path) : path.endsWith(".tsx") ? [path] : [];
});

const usage = new Map();
for (const file of walk("src")) {
  const text = readFileSync(file, "utf8");
  for (const match of text.matchAll(/className=(?:"([^"]*)"|\{`([^`]*)`\})/g)) {
    const value = (match[1] ?? match[2] ?? "").replace(/\$\{[^}]*\}/g, " ");
    for (const name of value.split(/\s+/).filter((token) => /^[a-z][a-z0-9_-]*$/.test(token))) {
      if (!usage.has(name)) usage.set(name, new Set());
      usage.get(name).add(file.replace("src/", ""));
    }
  }
}

const groups = new Map();
for (const [name, files] of [...usage].sort(([a], [b]) => a.localeCompare(b))) {
  const owner = [...files][0].replace(/\.tsx$/, "").replace("components/", "");
  const key = files.size > 1 ? "shared" : owner;
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(name);
}

const tokens = [...readFileSync("src/styles/tokens.css", "utf8").matchAll(/^\s*(--mochi-[a-z0-9-]+):\s*(.+?);\s*$/gm)];
let out = "# Theme hooks\n\n_Generated by `node scripts/list-theme-hooks.mjs`. Do not edit by hand._\n\n";
out += `Every launcher screen is built from ${usage.size} stable class names and ${tokens.length} design tokens. A theme can restyle any of them from \`theme.css\`, or retint everything at once from the tokens in \`theme.json\`.\n\n`;
out += "## Classes\n\n";
for (const [group, names] of [...groups].sort(([a], [b]) => a.localeCompare(b))) out += `**${group}** — ${names.map((name) => `\`.${name}\``).join(" ")}\n\n`;
out += "## Tokens\n\nToken \`--mochi-foo-bar\` is set from \`theme.json\` as \`fooBar\` in the section shown in the architecture guide.\n\n| Token | Default |\n| --- | --- |\n";
for (const [, name, value] of tokens) out += `| \`${name}\` | \`${value.replace(/\|/g, "\\|")}\` |\n`;
writeFileSync("docs/theme-hooks.md", out);
console.log(`docs/theme-hooks.md: ${usage.size} classes, ${tokens.length} tokens`);
